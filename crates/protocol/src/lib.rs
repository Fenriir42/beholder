//! Beholder wire protocol: WebSocket messages, HTTP bodies, and the frame codec.
//!
//! Evolution rule (ADR-0003): postcard is not self-describing, so the only
//! compatible change is appending an enum variant. Anything else bumps
//! [`PROTOCOL_VERSION`].

#[cfg(feature = "codec")]
pub mod codec;
pub mod http;

use core::fmt;

use beholder_core::{
    Campaign, CampaignEvent, CampaignId, CampaignOp, CampaignTitle, CommandId, InviteCode, Seq,
    UnixMillis, User, UserId, ValidationError,
};
use serde::{Deserialize, Serialize};

/// Bumped on every incompatible wire change.
pub const PROTOCOL_VERSION: u16 = 1;

/// HTTP header carrying [`PROTOCOL_VERSION`] on HTTPS requests.
pub const PROTOCOL_HEADER: &str = "x-beholder-protocol";

/// Opaque session token: 32 random bytes. `Debug` never prints it.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct SessionToken(pub [u8; 32]);

impl SessionToken {
    /// Hex form for `Authorization: Bearer` headers and the OS keyring.
    pub fn to_hex(&self) -> String {
        // Same 32-byte hex encoding as image hashes.
        beholder_core::ImageHash(self.0).to_hex()
    }

    /// Parses the hex form.
    pub fn from_hex(s: &str) -> Option<Self> {
        beholder_core::ImageHash::from_hex(s).map(|h| Self(h.0))
    }
}

impl fmt::Debug for SessionToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("SessionToken(***)")
    }
}

/// A message from client to server over the WebSocket.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ClientMsg {
    /// First message on every connection.
    Hello(Hello),
    /// A user action; answered by `Ack` or `Reject`, safe to resend.
    Command(Command),
    /// Liveness check; the server answers `Pong` with the same `t`.
    Ping {
        /// Opaque client value (usually a monotonic clock), echoed back.
        t: u64,
    },
}

/// Opens a session and asks for everything missed since `known`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Hello {
    /// The client's [`PROTOCOL_VERSION`].
    pub protocol_version: u16,
    /// Token from login.
    pub session_token: SessionToken,
    /// Campaigns in the client cache, with the last seq applied to each.
    pub known: Vec<(CampaignId, Seq)>,
}

/// A user action, identified by a UUIDv7 so the server can deduplicate it.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Command {
    /// UUIDv7 generated by the client when the action was taken.
    pub id: CommandId,
    /// What to do.
    pub kind: CommandKind,
}

/// The action a [`Command`] carries.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum CommandKind {
    /// Create a campaign with the sender as DM. The client picks the id
    /// (UUIDv7) so it can show the campaign before the server answers.
    CreateCampaign {
        /// New campaign id.
        campaign_id: CampaignId,
        /// Initial title.
        title: CampaignTitle,
    },
    /// Join the campaign that currently owns `code`.
    JoinCampaign {
        /// Code typed by the user.
        code: InviteCode,
    },
    /// Change something in an existing campaign.
    Campaign {
        /// Target campaign.
        campaign_id: CampaignId,
        /// The change.
        op: CampaignOp,
    },
}

/// A message from server to client over the WebSocket.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ServerMsg {
    /// The session is open. Followed by `Events` or `Snapshot` per campaign.
    HelloOk(HelloOk),
    /// The session was refused; the server closes the connection after this.
    HelloErr(HelloError),
    /// The command was applied (or had already been applied).
    Ack {
        /// Command id.
        id: CommandId,
        /// Seq of the last event it produced, if it produced any.
        seq: Option<Seq>,
    },
    /// The command was refused and will never be applied; roll it back.
    Reject {
        /// Command id.
        id: CommandId,
        /// Why.
        reason: RejectReason,
    },
    /// New events for one campaign, already filtered for this recipient.
    /// Gaps in `seq` are normal: they are events this user may not see.
    Events {
        /// Campaign.
        campaign_id: CampaignId,
        /// Events in seq order.
        events: Vec<EventEnvelope>,
    },
    /// Full state of one campaign, filtered for this recipient. Replaces
    /// whatever the client had for it.
    Snapshot {
        /// Seq the state is current at.
        seq: Seq,
        /// The state.
        campaign: Campaign,
    },
    /// The user is no longer a member; drop the campaign from the cache.
    CampaignRemoved {
        /// Campaign.
        campaign_id: CampaignId,
    },
    /// Who is online in a campaign, sent after `HelloOk` and on join.
    Presence {
        /// Campaign.
        campaign_id: CampaignId,
        /// Members currently connected.
        online: Vec<UserId>,
    },
    /// One member came online or went offline.
    PresenceChanged {
        /// Campaign.
        campaign_id: CampaignId,
        /// Member.
        user_id: UserId,
        /// New state.
        online: bool,
    },
    /// Answer to `Ping`.
    Pong {
        /// The client's value.
        t: u64,
    },
}

/// Sent once the session is accepted.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct HelloOk {
    /// The logged-in account.
    pub user: User,
    /// Every campaign the user belongs to. Cached campaigns missing from this
    /// list must be dropped.
    pub campaigns: Vec<CampaignId>,
    /// A replacement token. Store it; the old one stops working once the new
    /// one has been used.
    pub rotated_token: Option<SessionToken>,
}

/// Why a session was refused.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum HelloError {
    /// The client must be updated to speak `server_version`.
    UpdateRequired {
        /// The server's [`PROTOCOL_VERSION`].
        server_version: u16,
    },
    /// The token is unknown or expired; log in again.
    InvalidSession,
}

/// Why a command was refused.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum RejectReason {
    /// The user's role doesn't allow it.
    Forbidden,
    /// The campaign doesn't exist or the user isn't a member.
    NotFound,
    /// No campaign uses this invite code.
    InvalidInviteCode,
    /// A field failed validation.
    Invalid(ValidationError),
    /// The referenced image was never uploaded.
    UnknownImage,
    /// The command id is already used by a different command.
    IdConflict,
    /// The command is older than the server's deduplication window, so it
    /// can't be applied safely.
    Expired,
    /// Too many attempts; try again later.
    RateLimited,
}

/// One event of a campaign log, as delivered to a client.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct EventEnvelope {
    /// Position in the campaign log.
    pub seq: Seq,
    /// When the server recorded it.
    pub ts: UnixMillis,
    /// Who caused it.
    pub actor: UserId,
    /// What happened.
    pub event: CampaignEvent,
}
